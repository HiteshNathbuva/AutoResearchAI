import { useEffect, useMemo, useState } from "react";
import { Link } from "react-router-dom";
import { api } from "../services/api";

export default function KnowledgeHub() {
  const [items, setItems] = useState([]);
  const [query, setQuery] = useState("");
  const [error, setError] = useState("");
  const [status, setStatus] = useState("loading");

  useEffect(() => {
    api.sessions()
      .then((d) => { setItems(d.sessions); setStatus("ready"); })
      .catch((e) => { setError(e.message); setStatus("ready"); });
  }, []);

  const reports = useMemo(() => items.filter((s) => s.has_report), [items]);
  const filtered = useMemo(() => {
    const q = query.trim().toLowerCase();
    return q ? reports.filter((s) => s.query.toLowerCase().includes(q)) : reports;
  }, [reports, query]);

  return (
    <section className="space-y-8">
      <div>
        <p className="text-cyan-300">Your library</p>
        <h1 className="mt-1 text-3xl font-bold">Knowledge Hub</h1>
        <p className="mt-3 max-w-2xl text-slate-400">Browse and organize every completed research report generated by AutoResearchAI.</p>
      </div>
      {error && <p role="alert" className="rounded-lg bg-red-500/15 p-3 text-red-200">{error}</p>}
      {status === "loading" && !error && <p className="text-slate-400">Loading your knowledge base…</p>}
      {!error && status === "ready" && (
        <>
          <input
            value={query}
            onChange={(e) => setQuery(e.target.value)}
            placeholder="Search saved reports…"
            aria-label="Search saved reports"
            className="w-full max-w-md rounded-xl border border-white/15 bg-slate-900 p-3 text-white placeholder:text-slate-500"
          />
          {filtered.length === 0 ? (
            <div className="rounded-xl border border-dashed border-white/15 p-10 text-center text-slate-400">
              <p>{reports.length === 0 ? "No finished reports yet. Generate a report from the Research page and it will appear here." : "No reports match your search."}</p>
              {reports.length === 0 && <Link to="/" className="mt-3 inline-block rounded-lg bg-cyan-500 px-4 py-2 font-semibold text-slate-950">Start research</Link>}
            </div>
          ) : (
            <div className="grid gap-4 sm:grid-cols-2 lg:grid-cols-3">
              {filtered.map((s) => (
                <Link key={s.session_id} to={`/reports/${s.session_id}`} className="rounded-xl border border-white/10 bg-slate-900 p-5 transition hover:border-cyan-400/60">
                  <p className="line-clamp-3 font-semibold">{s.query}</p>
                  <p className="mt-3 text-xs text-slate-400">{s.confidence || "Unverified"} confidence · {s.reading_time || 1} min read</p>
                  <p className="mt-1 text-xs text-slate-500">{new Date(s.updated_at).toLocaleDateString()}</p>
                </Link>
              ))}
            </div>
          )}
        </>
      )}
    </section>
  );
}
